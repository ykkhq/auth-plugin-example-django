# Runs right after FLOWS/ORDER are defined: drop everything the flow doesn't use.
FILTER = """
// ---- single-flow page, generated by docs/gen_mcp_flow_pages.py -- do not edit
{
  const keep = %(key)s, overrides = %(nodes)s, edgeOverrides = %(edges)s, first = %(first)s;
  const used = new Set(FLOWS[keep].steps.map(s => s.e));
  const ids = new Set(EDGES.filter(e => used.has(e.id)).flatMap(e => [e.s, e.t]));
  for (let grew = true; grew;) {  // the boxes around kept nodes
    grew = false;
    for (const n of NODES) if (ids.has(n.id) && n.parent && !ids.has(n.parent)) { ids.add(n.parent); grew = true; }
  }
  for (let i = EDGES.length; i--;) if (!used.has(EDGES[i].id)) EDGES.splice(i, 1);
  for (let i = NODES.length; i--;) if (!ids.has(NODES[i].id)) NODES.splice(i, 1);
  for (const n of NODES) Object.assign(n, overrides[n.id] || {});
  for (const e of EDGES) Object.assign(e, edgeOverrides[e.id] || {});
  for (const id of first) {  // stacked groups lay out children in NODES order
    const n = NODES.splice(NODES.findIndex(m => m.id === id), 1)[0];
    NODES.splice(NODES.findIndex(m => m.parent === n.parent), 0, n);
  }
  for (const k of Object.keys(FLOWS)) if (k !== keep && k !== 'all') delete FLOWS[k];
  FLOWS.all.name = 'Components';
  FLOWS.all.desc = 'Only the components of this flow. Pick the flow tab to step through it.';
  ORDER.splice(0, ORDER.length, keep, 'all');
}
"""

LINKS = " · ".join(f'<a href="{p["file"]}">{p["title"]}</a>' for p in PAGES.values())


def render(key, page):
    html = SOURCE.read_text()

    def rep(old, new):
        nonlocal html
        if html.count(old) != 1:
            sys.exit(f"{SOURCE.name} changed: expected one {old[:50]!r}")
        html = html.replace(old, new)

    rep("<title>Manufacturing Auth Flows v4</title>", f"<title>{page['title']} Flow</title>")
    rep('auth flows <span style="font-weight:500;color:var(--muted)">v4</span></h1>',
        f'{page["title"]} <span style="font-weight:500;color:var(--muted)">flow</span></h1>')
    old_sub = ("<p>Kong Gateway 3.16 + AI Gateway 2.2 on Konnect · Auth0 OIDC · Django REST Framework · "
               "MCP (apikey + Auth0 user login)</p>")
    rep(old_sub, f'<p>{page["sub"]}</p>\n    <p style="font-size:12px">MCP flows: {LINKS} · '
                 f'<a href="auth-flow-v4.html">all auth flows</a></p>')
    rep("const byId = ", FILTER % {"key": json.dumps(key), "nodes": json.dumps(page["nodes"]),
                                    "edges": json.dumps(page.get("edges", {})),
                                    "first": json.dumps(page.get("first", []))} + "\nconst byId = ")
    rep("flow: 'web', step: 0", "flow: ORDER[0], step: 0")
    rep("<!doctype html>\n", "<!doctype html>\n<!-- GENERATED by docs/gen_mcp_flow_pages.py from auth-flow-v4.html -- do not edit -->\n")
    return html


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a page is out of date")
    args = ap.parse_args()
    outputs = {DOCS / p["file"]: render(k, p) for k, p in PAGES.items()}
    if args.check:
        stale = [p.name for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            sys.exit(f"out of date: {', '.join(stale)}; run docs/gen_mcp_flow_pages.py")
        print(f"up to date: {len(outputs)} pages")
        return
    for path, text in outputs.items():
        path.write_text(text)
    print("wrote " + ", ".join(f"docs/{p.name}" for p in outputs))


if __name__ == "__main__":
    main()
