"""Generate one page per MCP flow (docs/mcp-flow-*.html) from docs/auth-flow-v4.html.

Each page keeps only that flow: its steps, the edges they use and the
components on those edges (plus the boxes around them). Node rows that
belong to other flows are replaced by the ones below. Re-run after
changing docs/auth-flow-v4.html:

    python3 docs/gen_mcp_flow_pages.py          # writes the pages
    python3 docs/gen_mcp_flow_pages.py --check  # exit 1 if a page is out of date
"""
