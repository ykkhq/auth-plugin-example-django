def server(resource, tools, oidc=False):
    root, upstream = (OIDC_MCP_ROOT, OIDC_UPSTREAM_ROOT) if oidc else (MCP_ROOT, UPSTREAM_ROOT)
    name = f"mfg-oidc-{resource}-mcp" if oidc else f"mfg-{resource}-mcp"
    title = f"Manufacturing {resource.replace('-', ' ').title()}" + (" (OIDC)" if oidc else "")
    # per-user API keys, so usage is metered per consumer. Auth strategy by name:
    # it lives in kong/ai-gateway-billing.yaml, which is applied first (a !ref
    # to an already existing strategy fails to resolve on update).
    access = {"acl_attribute_type": "consumer", "auth_strategies": ["mcp-key-auth"]}
    if oidc:
        # Auth0 bearer JWT (kong/ai-gateway-oidc.yaml). metadata turns on the MCP
        # OAuth2 flow: 401 + WWW-Authenticate pointing at the metadata document,
        # which must sit under the server's own route.
        access = {
            "acl_attribute_type": "consumer",
            "auth_strategies": ["mcp-auth0-oidc"],
            # consumer groups from the token's roles; every tool has its own acls below
            "default_tool_acls": {"allow": ["admin"]},
            "metadata": {
                "resource": OIDC_RESOURCE,
                "authorization_servers": ["__AUTH0_ISSUER_URL__"],
                "endpoint": f"{root}/{resource}/.well-known/oauth-protected-resource",
            },
        }
    return {
        "ref": name,
        "ai_gateway": "__LOOKUP__",
        "name": name,
        "display_name": title,
        "type": "conversion-listener",
        "config": {
            "url": f"{upstream}/{resource}",
            "route": {
                "paths": [f"{root}/{resource}"],
                "strip_path": True,
                "protocols": ["http", "https"],
            },
            # Orders and purchase orders carry nested lines.
            "max_request_body_size": 32768,
            "server": {"timeout": 60000, "forward_client_headers": True},
        },
        "access": access,
        # the OIDC servers forward the client's Authorization header instead of a key
        "tools": [
            {**place(t, root), "access": {"acls": {"allow": tool_roles(resource, t)}}} if oidc
            else place(t, root, {"apikey": [UPSTREAM_APIKEY]})
            for t in tools
        ],
    }


def tool_roles(resource, tool):
    """Consumer groups (Auth0 roles) allowed to see and call a tool."""
    method = tool["method"]
    roles = ["admin"]
    if method != "DELETE":
        roles.insert(0, "manager")
        if resource in SALES_WRITE or (resource in SALES_READ and method == "GET"):
            roles.insert(0, "sales")
    return roles


def place(tool, root, headers=None):
    """A tool with its path under root (and optional upstream headers right after it)."""
    out = {}
    for key, value in tool.items():
        # copies: the same tool goes into several files (no YAML anchors)
        out[key] = f"{root}/{value}" if key == "path" else copy.deepcopy(value)
        if key == "path" and headers:
            out["headers"] = headers
    return out


def load_schema():
    sys.path.insert(0, str(ROOT))
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "inventory_management.settings")
    import django

    django.setup()
    from drf_spectacular.generators import SchemaGenerator

    return SchemaGenerator().get_schema(request=None, public=True)


def resolve(node, components):
    """Inline $refs and drop OpenAPI-only keywords, giving plain JSON Schema."""
    if isinstance(node, dict):
        if "$ref" in node:
            name = node["$ref"].rsplit("/", 1)[-1]
            return resolve(copy.deepcopy(components[name]), components)
        # drf-spectacular models "email or blank" as oneOf [email, maxLength 0]; keep
        # the real variant so tool schemas stay flat (blank is simply omitted).
        if "oneOf" in node and len(node) == 1:
            variants = [v for v in node["oneOf"] if v.get("maxLength") != 0]
            if len(variants) == 1:
                return resolve(variants[0], components)
        return {k: resolve(v, components) for k, v in node.items() if k not in DROP_KEYS}
    if isinstance(node, list):
        return [resolve(v, components) for v in node]
    return node


def resource_of(path):
    return path[len(API_PREFIX):].split("/", 1)[0]


def tool_name(method, path):
    parts = path[len(API_PREFIX):].strip("/").split("/")
    resource = parts[0]
    singular = SINGULAR.get(resource, resource.rstrip("s"))
    if len(parts) == 1:
        if resource == "shipping-schedule":
            return "get-shipping-schedule"
        return {"get": f"list-{resource}", "post": f"create-{singular}"}[method]
    if len(parts) == 2:
        verb = {"get": "get", "put": "update", "patch": "patch", "delete": "delete"}[method]
        return f"{verb}-{singular}"
    return f"{parts[2]}-{singular}"


def build_tool(method, path, op, components):
    summary = (op.get("summary") or "").strip()
    tool = {
        "name": tool_name(method, path),
        "description": (op.get("description") or "").strip() or summary,
        "method": method.upper(),
        # route path + rest of the API path (place() prepends the route path);
        # the gateway strips the route path and appends the rest to the upstream
        "path": path[len(API_PREFIX):],
    }
    params = []
    for p in op.get("parameters", []):
        param = {
            "name": p["name"],
            "in": p["in"],
            "required": p.get("required", False),
            "schema": resolve(p.get("schema", {"type": "string"}), components),
        }
        if p.get("description"):
            param["description"] = p["description"]
        params.append(param)
    if params:
        tool["parameters"] = params
    body = op.get("requestBody", {}).get("content", {}).get("application/json")
    if body:
        tool["request_body"] = {
            "required": op["requestBody"].get("required", False),
            "content": {"application/json": {"schema": resolve(body["schema"], components)}},
        }
    annotations = {"title": summary.rstrip(".") or tool["name"]}
    if method == "get":
        annotations["read_only_hint"] = True
    if method == "delete":
        annotations["destructive_hint"] = True
    if method in ("put", "delete"):
        annotations["idempotent_hint"] = True
    tool["annotations"] = annotations
    return tool


class Dumper(__import__("yaml").SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def dump(data):
    import yaml

    return yaml.dump(data, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=100)


def env(name):
    return '${{ env "%s" }}' % name


def gw_config(by_resource):
    """decK state for the Kong GW MCP server: tool routes (conversion-only) + one listener."""
    services = [{
        # the listener answers MCP itself; this upstream is never called
        "name": "django-mcp",
        "host": "django",
        "port": 3333,
        "path": "/api",
        "routes": [{
            "name": "django-route-gw-mcp",
            "paths": [GW_MCP_PATH],
            # streamable HTTP: POST messages, GET stream, DELETE session; GET metadata
            "methods": ["GET", "POST", "DELETE"],
            "protocols": ["https"],
        }],
    }]
    plugins = [
        {
            "name": "ai-mcp-proxy",
            "instance_name": "gw-mcp-listener",
            "route": "django-route-gw-mcp",
            "config": {
                "mode": "listener",
                "server": {"tag": GW_MCP_TAG, "timeout": 60000, "forward_client_headers": True},
                # hand the caller's consumer groups to the tools' ACLs (tools/list filter)
                "include_consumer_groups": True,
                "logging": {"log_statistics": True, "log_payloads": False},
                "max_request_body_size": 32768,
            },
        },
        {
            # 401 + WWW-Authenticate: Bearer resource_metadata=<resource>/.well-known/
            # oauth-protected-resource (served on this route), then Auth0 login in the client
            "name": "ai-mcp-oauth2",
            "instance_name": "gw-mcp-auth0",
            "route": "django-route-gw-mcp",
            "config": {
                # also the token audience: Auth0 API identifier
                "resource": GW_MCP_RESOURCE,
                "authorization_servers": [env("DECK_AUTH0_ISSUER_URL")],
                "metadata_discovery_endpoint": env("DECK_AUTH0_ISSUER"),
                "scopes_supported": ["openid", "profile", "email"],
                # keep the JWT on the request: tool calls carry it to the tool routes
                "passthrough_credentials": True,
                # Auth0 roles -> consumer groups (no consumers); no known role = rejected
                "consumer_optional": True,
                "consumer_groups_claim": [ROLES_CLAIM],
                "consumer_groups_optional": False,
            },
        },
        {
            # per Auth0 user (virtual credential = sub); one tool call is several MCP requests
            "name": "rate-limiting",
            "instance_name": "gw-mcp-rate-limit",
            "route": "django-route-gw-mcp",
            "config": {"limit_by": "credential", "minute": 60, "hour": 1000, "policy": "local"},
        },
    ]
    for resource, tools in by_resource.items():
        route = f"django-route-gw-mcp-{resource}"
        services.append({
            "name": f"django-mcp-{resource}",
            "host": "django",
            "port": 3333,
            "path": f"/api/{resource}",
            "routes": [{
                "name": route,
                "paths": [f"{GW_TOOLS_ROOT}/{resource}"],
                "methods": ["GET", "POST", "PUT", "PATCH", "DELETE"],
                "protocols": ["https"],
            }],
        })
        plugins += [
            {
                "name": "ai-mcp-proxy",
                "instance_name": f"gw-mcp-tools-{resource}",
                "route": route,
                "tags": [GW_MCP_TAG],  # picked up by the listener's server.tag
                "config": {
                    "mode": "conversion-only",
                    # per-tool ACL by consumer group (Auth0 role)
                    "include_consumer_groups": True,
                    "tools": [{**place(t, GW_TOOLS_ROOT), "acl": {"allow": tool_roles(resource, t)}}
                              for t in tools],
                    "logging": {"log_statistics": True, "log_payloads": False},
                    "max_request_body_size": 32768,
                },
            },
            {
                # same Auth0 token as the listener (aud = the MCP resource); without one
                # the tool route is closed (it is reachable from outside like any route)
                "name": "openid-connect",
                "instance_name": f"gw-mcp-auth0-{resource}",
                "route": route,
                "config": {
                    "issuer": env("DECK_AUTH0_ISSUER"),
                    "ssl_verify": True,
                    "auth_methods": ["bearer"],
                    "audience_required": [GW_MCP_RESOURCE],
                    "cache_tokens_salt": env("DECK_OIDC_CACHE_TOKENS_SALT"),
                    "upstream_headers_claims": ["sub", "email"],
                    "upstream_headers_names": ["X-Authenticated-User", "X-Authenticated-Email"],
                    # tool calls are checked against the tool's acl here
                    "consumer_groups_claim": [ROLES_CLAIM],
                    "consumer_groups_optional": False,
                },
            },
            {
                # Django Basic auth (user1), as on every API route in kong/kong.yaml
                "name": "datakit",
                "instance_name": f"gw-mcp-basic-auth-{resource}",
                "route": route,
                "config": {"nodes": [
                    {"name": "creds", "type": "static",
                     "values": {"password": "awesome user1", "username": "user1"}},
                    {"name": "Create_Basic_Auth", "type": "jq",
                     "inputs": {"password": "creds.password", "username": "creds.username"},
                     "jq": '{ Authorization: ("Basic " + ("\\(.username):\\(.password)" | @base64)) }',
                     "output": "service_request.headers"},
                ]},
            },
        ]
    state = {
        "_format_version": "3.0",
        "_konnect": {"control_plane_name": "django-apigw"},
        "consumer_groups": [{"name": r} for r in ROLES],
        "services": services,
        "plugins": plugins,
    }
    return GW_HEADER + dump(state)


def public_spec(schema):
    """The API as published: Kong's /mfg base URL, apikey auth, no /api/auth or /api/schema."""
    spec = copy.deepcopy(schema)
    spec["info"]["description"] = (
        "Manufacturing REST API: items and bills of materials, suppliers and purchase "
        "orders, customers and dealers, sales orders, shipments and the shipping "
        "schedule. Call it through Kong with the `apikey` header. Every resource is "
        "also available as an MCP server at https://localhost:11443/mcp/mfg/<resource>."
    )
    spec["servers"] = [{"url": PUBLIC_SERVER, "description": "Kong Gateway (apikey)"}]
    spec["paths"] = {
        "/" + path[len(API_PREFIX):]: ops
        for path, ops in schema["paths"].items()
        if not path.startswith(SKIP)
    }
    scheme = {"type": "apiKey", "in": "header", "name": "apikey",
              "description": "Kong key-auth credential (demo key: test)."}
    spec.setdefault("components", {})["securitySchemes"] = {"apikey": scheme}
    spec["security"] = [{"apikey": []}]
    for ops in spec["paths"].values():
        for op in ops.values():
            if isinstance(op, dict):
                op.pop("security", None)
    return dump(spec)


