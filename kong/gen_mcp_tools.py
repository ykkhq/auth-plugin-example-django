#!/usr/bin/env python
"""Generate kong/ai-gateway.yaml (MCP servers) and kong/openapi/manufacturing-api.yaml (portal spec).

ai-gateway.yaml: one MCP server per REST resource, one tool per endpoint.
manufacturing-api.yaml: the public OpenAPI spec published to the Dev Portal
(kong/portal.yaml), i.e. the API as developers call it through Kong:
https://localhost:8443/mfg/<resource>/ with an `apikey` header.
portal/mcp-servers.md: the Dev Portal page listing every MCP server and its tools.

Reads the drf-spectacular OpenAPI schema straight from the Django project, so
the MCP tools always match the API. Re-run after changing any endpoint:

    .venv/bin/python kong/gen_mcp_tools.py          # writes both files
    .venv/bin/python kong/gen_mcp_tools.py --check  # exit 1 if either is out of date

Each resource gets its own MCP server at /mcp/mfg/<resource> (items,
suppliers, orders, ...), upstream https://<Kong GW>/mfg/<resource>.

Tool names: list-<plural>, get-/create-/update-/patch-/delete-<singular>, and
<action>-<singular> for custom actions (build-item, receive-purchase-order...).
"""
import argparse
import copy
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "kong" / "ai-gateway.yaml"
SPEC_OUT = ROOT / "kong" / "openapi" / "manufacturing-api.yaml"
MCP_PAGE_OUT = ROOT / "kong" / "portal" / "mcp-servers.md"
PUBLIC_MCP = "https://localhost:11443"
PUBLIC_SERVER = "https://localhost:8443/mfg"
API_PREFIX = "/api/"
MCP_ROOT = "/mcp/mfg"
UPSTREAM_ROOT = "https://host.docker.internal:8443/mfg"
# Kong GW key-auth credential (consumer user1) sent on every tool call: the AI GW
# authenticates MCP users with their own keys and strips them (hide_credentials).
UPSTREAM_APIKEY = "test"
SKIP = ("/api/auth/", "/api/schema")
SINGULAR = {
    "items": "item",
    "item-components": "item-component",
    "suppliers": "supplier",
    "customers": "customer",
    "purchase-orders": "purchase-order",
    "orders": "order",
    "shipments": "shipment",
    "shipping-statuses": "shipping-status",
    "shipping-schedule": "shipping-schedule",
}
# Schema keywords dropped from tool input schemas (OpenAPI-only, or response-only).
DROP_KEYS = {"readOnly", "writeOnly", "nullable"}

HEADER = """\
# GENERATED by kong/gen_mcp_tools.py from the Django OpenAPI schema -- do not
# edit by hand; change the API (views/serializers) and re-run the script.
#
# Kong AI Gateway 2.2 (Konnect AI Gateway "django-ai-gw"): exposes every
# Django REST endpoint as an MCP tool. Applied with kongctl, not decK:
#   kongctl apply -f kong/ai-gateway.yaml ...
# after kong/ai-gateway-billing.yaml (per-user keys and MCP metering).
#
# Upstream is the Kong Gateway 3.16 data plane (kong/kong.yaml), not Django
# directly, so apikey -> Basic auth bridging stays in one place.
#
#   MCP client --apikey--> AI GW :11443/mcp/mfg/<resource>  (one MCP server each)
#              --apikey--> Kong GW :8443/mfg/<resource>/...    (key-auth + datakit)
#              --Basic-->  Django :3333/api/<resource>/...
#
# Server notes: the AI GW container reaches the Kong GW DP's host-published
# https port; Kong GW serves kong/tls/server.crt for SNI host.docker.internal
# and the AI GW DP trusts its CA (kong/tls/ca.crt, see start_ai_dp.sh).
# MCP users authenticate to the AI GW with their own apikey (metered per user,
# kong/ai-gateway-billing.yaml); each tool sends Kong GW's key in its headers.
"""


def server(resource, tools):
    return {
        "ref": f"mfg-{resource}-mcp",
        "ai_gateway": "__LOOKUP__",
        "name": f"mfg-{resource}-mcp",
        "display_name": f"Manufacturing {resource.replace('-', ' ').title()}",
        "type": "conversion-listener",
        "config": {
            "url": f"{UPSTREAM_ROOT}/{resource}",
            "route": {
                "paths": [f"{MCP_ROOT}/{resource}"],
                "strip_path": True,
                "protocols": ["http", "https"],
            },
            # Orders and purchase orders carry nested lines.
            "max_request_body_size": 32768,
            "server": {"timeout": 60000, "forward_client_headers": True},
        },
        # per-user API keys, so usage is metered per consumer. Auth strategy by name:
        # it lives in kong/ai-gateway-billing.yaml, which is applied first (a !ref
        # to an already existing strategy fails to resolve on update).
        "access": {"acl_attribute_type": "consumer", "auth_strategies": ["mcp-key-auth"]},
        "tools": tools,
    }


def load_schema():
    sys.path.insert(0, str(ROOT))
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "inventory_management.settings")
    import django

    django.setup()
    from drf_spectacular.generators import SchemaGenerator

    return SchemaGenerator().get_schema(request=None, public=True)


def resolve(node, components):
    """Inline $refs and drop OpenAPI-only keywords, giving plain JSON Schema."""
    if isinstance(node, dict):
        if "$ref" in node:
            name = node["$ref"].rsplit("/", 1)[-1]
            return resolve(copy.deepcopy(components[name]), components)
        # drf-spectacular models "email or blank" as oneOf [email, maxLength 0]; keep
        # the real variant so tool schemas stay flat (blank is simply omitted).
        if "oneOf" in node and len(node) == 1:
            variants = [v for v in node["oneOf"] if v.get("maxLength") != 0]
            if len(variants) == 1:
                return resolve(variants[0], components)
        return {k: resolve(v, components) for k, v in node.items() if k not in DROP_KEYS}
    if isinstance(node, list):
        return [resolve(v, components) for v in node]
    return node


def resource_of(path):
    return path[len(API_PREFIX):].split("/", 1)[0]


def tool_name(method, path):
    parts = path[len(API_PREFIX):].strip("/").split("/")
    resource = parts[0]
    singular = SINGULAR.get(resource, resource.rstrip("s"))
    if len(parts) == 1:
        if resource == "shipping-schedule":
            return "get-shipping-schedule"
        return {"get": f"list-{resource}", "post": f"create-{singular}"}[method]
    if len(parts) == 2:
        verb = {"get": "get", "put": "update", "patch": "patch", "delete": "delete"}[method]
        return f"{verb}-{singular}"
    return f"{parts[2]}-{singular}"


def build_tool(method, path, op, components):
    summary = (op.get("summary") or "").strip()
    tool = {
        "name": tool_name(method, path),
        "description": (op.get("description") or "").strip() or summary,
        "method": method.upper(),
        # route path + rest of the API path; the AI GW strips the route path
        # and appends the rest to config.url
        "path": f"{MCP_ROOT}/{path[len(API_PREFIX):]}",
        "headers": {"apikey": [UPSTREAM_APIKEY]},
    }
    params = []
    for p in op.get("parameters", []):
        param = {
            "name": p["name"],
            "in": p["in"],
            "required": p.get("required", False),
            "schema": resolve(p.get("schema", {"type": "string"}), components),
        }
        if p.get("description"):
            param["description"] = p["description"]
        params.append(param)
    if params:
        tool["parameters"] = params
    body = op.get("requestBody", {}).get("content", {}).get("application/json")
    if body:
        tool["request_body"] = {
            "required": op["requestBody"].get("required", False),
            "content": {"application/json": {"schema": resolve(body["schema"], components)}},
        }
    annotations = {"title": summary.rstrip(".") or tool["name"]}
    if method == "get":
        annotations["read_only_hint"] = True
    if method == "delete":
        annotations["destructive_hint"] = True
    if method in ("put", "delete"):
        annotations["idempotent_hint"] = True
    tool["annotations"] = annotations
    return tool


class Dumper(__import__("yaml").SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def dump(data):
    import yaml

    return yaml.dump(data, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=100)


def public_spec(schema):
    """The API as published: Kong's /mfg base URL, apikey auth, no /api/auth or /api/schema."""
    spec = copy.deepcopy(schema)
    spec["info"]["description"] = (
        "Manufacturing REST API: items and bills of materials, suppliers and purchase "
        "orders, customers and dealers, sales orders, shipments and the shipping "
        "schedule. Call it through Kong with the `apikey` header. Every resource is "
        "also available as an MCP server at https://localhost:11443/mcp/mfg/<resource>."
    )
    spec["servers"] = [{"url": PUBLIC_SERVER, "description": "Kong Gateway (apikey)"}]
    spec["paths"] = {
        "/" + path[len(API_PREFIX):]: ops
        for path, ops in schema["paths"].items()
        if not path.startswith(SKIP)
    }
    scheme = {"type": "apiKey", "in": "header", "name": "apikey",
              "description": "Kong key-auth credential (demo key: test)."}
    spec.setdefault("components", {})["securitySchemes"] = {"apikey": scheme}
    spec["security"] = [{"apikey": []}]
    for ops in spec["paths"].values():
        for op in ops.values():
            if isinstance(op, dict):
                op.pop("security", None)
    return dump(spec)


def mcp_page(servers):
    """Dev Portal page (MDC markdown) listing the MCP servers; Konnect has no portal
    publication for MCP servers, so the portal shows them as a page."""
    rows = []
    for srv in servers:
        path = srv["config"]["route"]["paths"][0]
        rows.append(f"| [{srv['display_name']}](#{path.rsplit('/', 1)[-1]}) | `{PUBLIC_MCP}{path}` | {len(srv['tools'])} |")
    sections = []
    for srv in servers:
        path = srv["config"]["route"]["paths"][0]
        name = path.rsplit("/", 1)[-1]
        tools = "\n".join(f"| `{t['name']}` | {t['description']} |" for t in srv["tools"])
        sections.append(f"""## {srv['display_name']} {{#{name}}}

`{PUBLIC_MCP}{path}`

```bash
claude mcp add --transport http mfg-{name} {PUBLIC_MCP}{path} --header "apikey: test"
```

| Tool | Description |
|---|---|
{tools}
""")
    return f"""---
title: "MCP servers"
description: "Every manufacturing API resource as an MCP server for AI agents."
---

::page-section
# MCP servers

Every API resource is also an MCP server on Kong AI Gateway, one server per
resource. Each tool calls the matching REST endpoint, so the
[API reference](/apis) documents its inputs and outputs. Connect with the
same `apikey` header as the REST API (demo key: `test`) over streamable HTTP.

| Server | Endpoint | Tools |
|---|---|---|
{chr(10).join(rows)}

Add only the servers an agent needs, to keep its tool list small.

{chr(10).join(sections)}
::
"""


def render():
    schema = load_schema()
    components = schema.get("components", {}).get("schemas", {})
    by_resource = {}
    for path, ops in schema["paths"].items():
        if path.startswith(SKIP):
            continue
        for method in ("get", "post", "put", "patch", "delete"):
            if method in ops:
                tool = build_tool(method, path, ops[method], components)
                by_resource.setdefault(resource_of(path), []).append(tool)
    names = [t["name"] for tools in by_resource.values() for t in tools]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        sys.exit(f"duplicate tool names: {sorted(dupes)}")
    servers = [server(resource, tools) for resource, tools in by_resource.items()]

    body = dump({"ai_gateway_mcp_servers": servers})
    # kongctl's !lookup tag can't be produced by SafeDumper, so splice it in.
    body = body.replace("ai_gateway: __LOOKUP__", "ai_gateway: !lookup {name: django-ai-gw}")
    spec_header = "# GENERATED by kong/gen_mcp_tools.py -- do not edit by hand.\n"
    outputs = {
        OUT: HEADER + body,
        SPEC_OUT: spec_header + public_spec(schema),
        MCP_PAGE_OUT: mcp_page(servers),
    }
    return outputs, f"{len(servers)} servers, {len(names)} tools, {len(names)} spec operations"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a generated file is out of date")
    args = ap.parse_args()
    outputs, count = render()
    names = ", ".join(str(p.relative_to(ROOT)) for p in outputs)
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items()
                 if not p.exists() or p.read_text() != text]
        if stale:
            sys.exit(f"out of date: {', '.join(stale)}; run kong/gen_mcp_tools.py")
        print(f"up to date: {names} ({count})")
        return
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"wrote {names} ({count})")


if __name__ == "__main__":
    main()
